def find_learning_sentences(segments: list, max_results: int = 3) -> list:
    """
    Whisper 세그먼트에서 학습에 적합한 문장 찾기
    
    Args:
        segments: Whisper가 반환한 세그먼트 리스트
        max_results: 최대 결과 수
    
    Returns:
        학습 문장 리스트
    """
    results = []
    
    for segment in segments:
        text = segment['text'].strip()
        start = segment['start']
        end = segment['end']
        
        for pattern, base_form, hint_en in LEARNING_PATTERNS:
            match = re.search(pattern, text)
            if match:
                full_sentence = match.group(0).strip()
                answer_word = match.group(2)
                
                # 최소 길이 체크
                if len(full_sentence) >= 6:
                    results.append({
                        'start_sec': int(start),
                        'end_sec': int(end) + 2,
                        'full_sentence': full_sentence,
                        'answer_word': answer_word,
                        'base_form': base_form,
                        'hint_en': hint_en,
                        'original_text': text,
                    })
                break  # 한 세그먼트에서 하나만
    
    # 중복 answer_word 제거
    seen = set()
    unique = []
    for r in results:
        if r['answer_word'] not in seen:
            seen.add(r['answer_word'])
            unique.append(r)
    
    return unique[:max_results]

